import os
import sqlite3
import threading
from datetime import datetime, timezone


BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB_PATH = os.path.join(BASE_DIR, "data", "albaranes.db")
DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
_DB_INITIALIZED = False
_DB_INIT_LOCK = threading.Lock()

class PostgresCursor:
    def __init__(self, cursor):
        self._cursor = cursor

    def execute(self, query, params=None):
        self._cursor.execute(query.replace("?", "%s"), params or ())
        return self

    def executemany(self, query, params):
        self._cursor.executemany(query.replace("?", "%s"), params)
        return self

    def fetchall(self):
        return self._cursor.fetchall()

    def fetchone(self):
        return self._cursor.fetchone()

    @property
    def rowcount(self):
        return self._cursor.rowcount


class PostgresConnection:
    def __init__(self, connection):
        self._connection = connection

    def cursor(self):
        return PostgresCursor(self._connection.cursor())

    def execute(self, query, params=None):
        cursor = self.cursor()
        return cursor.execute(query, params)

    def executemany(self, query, params):
        cursor = self.cursor()
        return cursor.executemany(query, params)

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()

    def close(self):
        self._connection.close()

def _ensure_almacenes(connection):
    connection.execute(
        "INSERT INTO almacenes (nombre) VALUES (?) ON CONFLICT (nombre) DO NOTHING",
        ("Nave 1",),
    )
    connection.execute(
        "INSERT INTO almacenes (nombre) VALUES (?) ON CONFLICT (nombre) DO NOTHING",
        ("Nave 2",),
    )
    return {
        nombre: fila[0]
        for nombre in ("Nave 1", "Nave 2")
        if (
            fila := connection.execute(
                "SELECT id FROM almacenes WHERE nombre=?", (nombre,)
            ).fetchone()
        )
    }


def _postgres_columns(connection, table):
    cursor = connection.cursor()
    cursor.execute(
        """SELECT column_name FROM information_schema.columns
        WHERE table_schema='public' AND table_name=?""",
        (table,),
    )
    return {row[0] for row in cursor.fetchall()}


def _init_postgres(connection):
    cursor = connection.cursor()
    cursor.execute("""CREATE TABLE IF NOT EXISTS almacenes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre TEXT NOT NULL UNIQUE
    )""")
    almacenes = _ensure_almacenes(connection)
    cursor.execute("""CREATE TABLE IF NOT EXISTS app_migrations (
        nombre TEXT PRIMARY KEY, aplicada_en TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    )""")
    cursor.execute("""CREATE TABLE IF NOT EXISTS albaranes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre TEXT, empresa TEXT, solicitado_por TEXT, materiales TEXT,
        comentario TEXT, envio_recogida TEXT, estado TEXT,
        observaciones TEXT, mensaje_final TEXT, fecha TEXT, foto_preparacion TEXT,
        numero_serie TEXT, procesado_en TEXT
    )""")
    cursor.execute("""CREATE TABLE IF NOT EXISTS equipos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre TEXT NOT NULL, cantidad INTEGER NOT NULL, numero_serie TEXT NOT NULL,
        seccion TEXT NOT NULL, fecha_alta TEXT NOT NULL
    )""")
    cursor.execute("""CREATE TABLE IF NOT EXISTS albaranes_finalizados (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        albaran_id INTEGER NOT NULL, fecha TEXT, nombre TEXT, empresa TEXT,
        solicitado_por TEXT, material TEXT, unidades TEXT,
        UNIQUE (albaran_id, material, unidades)
    )""")
    cursor.execute("""CREATE TABLE IF NOT EXISTS almacen_secciones (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        almacen_id INTEGER NOT NULL,
        nombre TEXT NOT NULL, descripcion TEXT, filas INTEGER NOT NULL DEFAULT 1,
        columnas INTEGER NOT NULL DEFAULT 1, alto_m REAL NOT NULL DEFAULT 2.5,
        ancho_m REAL NOT NULL DEFAULT 10, fondo_m REAL NOT NULL DEFAULT 10,
        capacidad_palets INTEGER NOT NULL DEFAULT 1, activa INTEGER NOT NULL DEFAULT 1,
        CONSTRAINT uq_almacen_secciones_nave_nombre UNIQUE (almacen_id, nombre),
        CONSTRAINT fk_almacen_secciones_almacenes FOREIGN KEY (almacen_id) REFERENCES almacenes(id)
    )""")
    cursor.execute("""CREATE TABLE IF NOT EXISTS almacen_ubicaciones (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        seccion_id INTEGER NOT NULL, almacen_id INTEGER NOT NULL,
        codigo TEXT NOT NULL, fila INTEGER NOT NULL,
        columna INTEGER NOT NULL, capacidad_palets INTEGER NOT NULL DEFAULT 1,
        alto_m REAL NOT NULL DEFAULT 2.5, ancho_m REAL NOT NULL DEFAULT 1.2,
        fondo_m REAL NOT NULL DEFAULT 1.2, activa INTEGER NOT NULL DEFAULT 1,
        FOREIGN KEY (seccion_id) REFERENCES almacen_secciones(id),
        CONSTRAINT uq_almacen_ubicaciones_nave_codigo UNIQUE (almacen_id, codigo),
        CONSTRAINT fk_almacen_ubicaciones_almacenes FOREIGN KEY (almacen_id) REFERENCES almacenes(id)
    )""")
    cursor.execute("""CREATE TABLE IF NOT EXISTS almacen_stock (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ubicacion_id INTEGER NOT NULL, material TEXT NOT NULL,
        codigo_material TEXT NOT NULL DEFAULT '', palets INTEGER NOT NULL DEFAULT 0,
        unidades_por_palet INTEGER NOT NULL DEFAULT 1, unidades_sueltas INTEGER NOT NULL DEFAULT 0,
        actualizado TEXT NOT NULL, UNIQUE (ubicacion_id, material, codigo_material),
        FOREIGN KEY (ubicacion_id) REFERENCES almacen_ubicaciones(id)
    )""")
    cursor.execute("""CREATE TABLE IF NOT EXISTS almacen_movimientos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        fecha TEXT NOT NULL, tipo TEXT NOT NULL, ubicacion_id INTEGER NOT NULL,
        material TEXT NOT NULL, codigo_material TEXT NOT NULL DEFAULT '', palets INTEGER NOT NULL DEFAULT 0,
        unidades_por_palet INTEGER NOT NULL DEFAULT 1, unidades_sueltas INTEGER NOT NULL DEFAULT 0,
        referencia TEXT, albaran_id INTEGER, FOREIGN KEY (ubicacion_id) REFERENCES almacen_ubicaciones(id)
    )""")
    if "almacen_id" not in _postgres_columns(connection, "almacen_secciones"):
        cursor.execute("ALTER TABLE almacen_secciones ADD COLUMN almacen_id INTEGER")
    cursor.execute(
        "UPDATE almacen_secciones SET almacen_id=? WHERE almacen_id IS NULL",
        (almacenes["Nave 1"],),
    )
    cursor.execute("ALTER TABLE almacen_secciones ALTER COLUMN almacen_id SET NOT NULL")
    if "almacen_id" not in _postgres_columns(connection, "almacen_ubicaciones"):
        cursor.execute("ALTER TABLE almacen_ubicaciones ADD COLUMN almacen_id INTEGER")
    cursor.execute(
        "UPDATE almacen_ubicaciones u SET almacen_id=sec.almacen_id "
        "FROM almacen_secciones sec WHERE sec.id=u.seccion_id AND u.almacen_id IS NULL"
    )
    cursor.execute("ALTER TABLE almacen_ubicaciones ALTER COLUMN almacen_id SET NOT NULL")
    cursor.execute("ALTER TABLE almacen_secciones DROP CONSTRAINT IF EXISTS almacen_secciones_nombre_key")
    cursor.execute("ALTER TABLE almacen_ubicaciones DROP CONSTRAINT IF EXISTS almacen_ubicaciones_codigo_key")
    cursor.execute("""DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname='uq_almacen_secciones_nave_nombre'
                  AND conrelid='almacen_secciones'::regclass
            ) THEN
                ALTER TABLE almacen_secciones
                ADD CONSTRAINT uq_almacen_secciones_nave_nombre UNIQUE (almacen_id, nombre);
            END IF;
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname='fk_almacen_secciones_almacenes'
                  AND conrelid='almacen_secciones'::regclass
            ) THEN
                ALTER TABLE almacen_secciones
                ADD CONSTRAINT fk_almacen_secciones_almacenes
                FOREIGN KEY (almacen_id) REFERENCES almacenes(id);
            END IF;
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname='uq_almacen_ubicaciones_nave_codigo'
                  AND conrelid='almacen_ubicaciones'::regclass
            ) THEN
                ALTER TABLE almacen_ubicaciones
                ADD CONSTRAINT uq_almacen_ubicaciones_nave_codigo UNIQUE (almacen_id, codigo);
            END IF;
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname='fk_almacen_ubicaciones_almacenes'
                  AND conrelid='almacen_ubicaciones'::regclass
            ) THEN
                ALTER TABLE almacen_ubicaciones
                ADD CONSTRAINT fk_almacen_ubicaciones_almacenes
                FOREIGN KEY (almacen_id) REFERENCES almacenes(id);
            END IF;
        END $$""")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_almacen_stock_ubicacion ON almacen_stock(ubicacion_id)")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_almacen_movimientos_fecha ON almacen_movimientos(fecha)")
    if "foto_preparacion" not in _postgres_columns(connection, "albaranes"):
        cursor.execute("ALTER TABLE albaranes ADD COLUMN foto_preparacion TEXT")
    if "numero_serie" not in _postgres_columns(connection, "albaranes"):
        cursor.execute("ALTER TABLE albaranes ADD COLUMN numero_serie TEXT")
    if "procesado_en" not in _postgres_columns(connection, "albaranes"):
        cursor.execute("ALTER TABLE albaranes ADD COLUMN procesado_en TEXT")
    cursor.execute(
        "UPDATE albaranes SET procesado_en=? "
        "WHERE estado='procesando' AND procesado_en IS NULL",
        (datetime.now(timezone.utc).isoformat(timespec="seconds"),),
    )
    _reset_nave1_once(connection, almacenes["Nave 1"])
    connection.commit()


def _init_sqlite(connection):
    cur = connection.cursor()
    cur.execute("PRAGMA foreign_keys=OFF")
    cur.execute("""CREATE TABLE IF NOT EXISTS almacenes (
        id INTEGER PRIMARY KEY AUTOINCREMENT, nombre TEXT NOT NULL UNIQUE
    )""")
    almacenes = _ensure_almacenes(connection)
    cur.execute("""CREATE TABLE IF NOT EXISTS app_migrations (
        nombre TEXT PRIMARY KEY, aplicada_en TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    )""")
    cur.execute("""CREATE TABLE IF NOT EXISTS albaranes (
        id INTEGER PRIMARY KEY AUTOINCREMENT, nombre TEXT, empresa TEXT,
        solicitado_por TEXT, materiales TEXT, comentario TEXT,
        envio_recogida TEXT, estado TEXT, observaciones TEXT,
        mensaje_final TEXT, fecha TEXT, foto_preparacion TEXT, numero_serie TEXT,
        procesado_en TEXT
    )""")
    columns = {row[1] for row in cur.execute("PRAGMA table_info(albaranes)").fetchall()}
    if "foto_preparacion" not in columns:
        cur.execute("ALTER TABLE albaranes ADD COLUMN foto_preparacion TEXT")
    if "numero_serie" not in columns:
        cur.execute("ALTER TABLE albaranes ADD COLUMN numero_serie TEXT")
    if "procesado_en" not in columns:
        cur.execute("ALTER TABLE albaranes ADD COLUMN procesado_en TEXT")
    cur.execute(
        "UPDATE albaranes SET procesado_en=? "
        "WHERE estado='procesando' AND procesado_en IS NULL",
        (datetime.now(timezone.utc).isoformat(timespec="seconds"),),
    )
    cur.execute("""CREATE TABLE IF NOT EXISTS equipos (
        id INTEGER PRIMARY KEY AUTOINCREMENT, nombre TEXT NOT NULL,
        cantidad INTEGER NOT NULL, numero_serie TEXT NOT NULL,
        seccion TEXT NOT NULL, fecha_alta TEXT NOT NULL
    )""")
    cur.execute("""CREATE TABLE IF NOT EXISTS albaranes_finalizados (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        albaran_id INTEGER NOT NULL, fecha TEXT, nombre TEXT, empresa TEXT,
        solicitado_por TEXT, material TEXT, unidades TEXT,
        UNIQUE (albaran_id, material, unidades)
    )""")
    cur.execute("""CREATE TABLE IF NOT EXISTS almacen_secciones (
        id INTEGER PRIMARY KEY AUTOINCREMENT, almacen_id INTEGER NOT NULL,
        nombre TEXT NOT NULL,
        descripcion TEXT, filas INTEGER NOT NULL DEFAULT 1, columnas INTEGER NOT NULL DEFAULT 1,
        alto_m REAL NOT NULL DEFAULT 2.5, ancho_m REAL NOT NULL DEFAULT 10,
        fondo_m REAL NOT NULL DEFAULT 10, capacidad_palets INTEGER NOT NULL DEFAULT 1,
        activa INTEGER NOT NULL DEFAULT 1, UNIQUE (almacen_id, nombre),
        FOREIGN KEY (almacen_id) REFERENCES almacenes(id)
    )""")
    cur.execute("""CREATE TABLE IF NOT EXISTS almacen_ubicaciones (
        id INTEGER PRIMARY KEY AUTOINCREMENT, seccion_id INTEGER NOT NULL,
        almacen_id INTEGER NOT NULL,
        codigo TEXT NOT NULL, fila INTEGER NOT NULL, columna INTEGER NOT NULL,
        capacidad_palets INTEGER NOT NULL DEFAULT 1, alto_m REAL NOT NULL DEFAULT 2.5,
        ancho_m REAL NOT NULL DEFAULT 1.2, fondo_m REAL NOT NULL DEFAULT 1.2,
        activa INTEGER NOT NULL DEFAULT 1, UNIQUE (almacen_id, codigo),
        FOREIGN KEY (almacen_id) REFERENCES almacenes(id),
        FOREIGN KEY (seccion_id) REFERENCES almacen_secciones(id)
    )""")
    cur.execute("""CREATE TABLE IF NOT EXISTS almacen_stock (
        id INTEGER PRIMARY KEY AUTOINCREMENT, ubicacion_id INTEGER NOT NULL,
        material TEXT NOT NULL, codigo_material TEXT NOT NULL DEFAULT '', palets INTEGER NOT NULL DEFAULT 0,
        unidades_por_palet INTEGER NOT NULL DEFAULT 1, unidades_sueltas INTEGER NOT NULL DEFAULT 0,
        actualizado TEXT NOT NULL, UNIQUE (ubicacion_id, material, codigo_material),
        FOREIGN KEY (ubicacion_id) REFERENCES almacen_ubicaciones(id)
    )""")
    cur.execute("""CREATE TABLE IF NOT EXISTS almacen_movimientos (
        id INTEGER PRIMARY KEY AUTOINCREMENT, fecha TEXT NOT NULL, tipo TEXT NOT NULL,
        ubicacion_id INTEGER NOT NULL, material TEXT NOT NULL, codigo_material TEXT NOT NULL DEFAULT '',
        palets INTEGER NOT NULL DEFAULT 0, unidades_por_palet INTEGER NOT NULL DEFAULT 1,
        unidades_sueltas INTEGER NOT NULL DEFAULT 0, referencia TEXT, albaran_id INTEGER,
        FOREIGN KEY (ubicacion_id) REFERENCES almacen_ubicaciones(id)
    )""")
    _migrate_sqlite_warehouse_tables(connection, almacenes["Nave 1"])
    cur.execute("CREATE INDEX IF NOT EXISTS idx_almacen_stock_ubicacion ON almacen_stock(ubicacion_id)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_almacen_movimientos_fecha ON almacen_movimientos(fecha)")
    _reset_nave1_once(connection, almacenes["Nave 1"])
    connection.commit()
    cur.execute("PRAGMA foreign_keys=ON")


def _reset_nave1_once(connection, nave1_id):
    migration = "reset_nave1_for_clean_start_20261001"
    if connection.execute(
        "SELECT 1 FROM app_migrations WHERE nombre=?", (migration,)
    ).fetchone():
        return

    connection.execute(
        "DELETE FROM almacen_movimientos WHERE ubicacion_id IN "
        "(SELECT id FROM almacen_ubicaciones WHERE almacen_id=?)",
        (nave1_id,),
    )
    connection.execute(
        "DELETE FROM almacen_stock WHERE ubicacion_id IN "
        "(SELECT id FROM almacen_ubicaciones WHERE almacen_id=?)",
        (nave1_id,),
    )
    connection.execute("DELETE FROM almacen_ubicaciones WHERE almacen_id=?", (nave1_id,))
    connection.execute("DELETE FROM almacen_secciones WHERE almacen_id=?", (nave1_id,))
    connection.execute("INSERT INTO app_migrations (nombre) VALUES (?)", (migration,))


def _migrate_sqlite_warehouse_tables(connection, nave1_id):
    cur = connection.cursor()
    section_columns = {
        row[1] for row in cur.execute("PRAGMA table_info(almacen_secciones)").fetchall()
    }
    location_columns = {
        row[1] for row in cur.execute("PRAGMA table_info(almacen_ubicaciones)").fetchall()
    }
    section_sql = cur.execute(
        "SELECT sql FROM sqlite_master WHERE type='table' AND name='almacen_secciones'"
    ).fetchone()[0]
    location_sql = cur.execute(
        "SELECT sql FROM sqlite_master WHERE type='table' AND name='almacen_ubicaciones'"
    ).fetchone()[0]
    if (
        "almacen_id" in section_columns
        and "almacen_id" in location_columns
        and "nombre TEXT NOT NULL UNIQUE" not in section_sql
        and "codigo TEXT NOT NULL UNIQUE" not in location_sql
    ):
        return

    if "almacen_id" in section_columns:
        section_warehouse = "almacen_id"
    else:
        section_warehouse = str(int(nave1_id))
    cur.execute("""CREATE TABLE almacen_secciones_nueva (
        id INTEGER PRIMARY KEY AUTOINCREMENT, almacen_id INTEGER NOT NULL,
        nombre TEXT NOT NULL, descripcion TEXT,
        filas INTEGER NOT NULL DEFAULT 1, columnas INTEGER NOT NULL DEFAULT 1,
        alto_m REAL NOT NULL DEFAULT 2.5, ancho_m REAL NOT NULL DEFAULT 10,
        fondo_m REAL NOT NULL DEFAULT 10, capacidad_palets INTEGER NOT NULL DEFAULT 1,
        activa INTEGER NOT NULL DEFAULT 1, UNIQUE (almacen_id, nombre),
        FOREIGN KEY (almacen_id) REFERENCES almacenes(id)
    )""")
    cur.execute(
        "INSERT INTO almacen_secciones_nueva "
        "(id, almacen_id, nombre, descripcion, filas, columnas, alto_m, ancho_m, "
        "fondo_m, capacidad_palets, activa) "
        "SELECT id, " + section_warehouse + ", nombre, descripcion, filas, columnas, "
        "alto_m, ancho_m, fondo_m, capacidad_palets, activa FROM almacen_secciones"
    )
    cur.execute("""CREATE TABLE almacen_ubicaciones_nueva (
        id INTEGER PRIMARY KEY AUTOINCREMENT, seccion_id INTEGER NOT NULL,
        almacen_id INTEGER NOT NULL,
        codigo TEXT NOT NULL, fila INTEGER NOT NULL, columna INTEGER NOT NULL,
        capacidad_palets INTEGER NOT NULL DEFAULT 1, alto_m REAL NOT NULL DEFAULT 2.5,
        ancho_m REAL NOT NULL DEFAULT 1.2, fondo_m REAL NOT NULL DEFAULT 1.2,
        activa INTEGER NOT NULL DEFAULT 1, UNIQUE (almacen_id, codigo),
        FOREIGN KEY (almacen_id) REFERENCES almacenes(id),
        FOREIGN KEY (seccion_id) REFERENCES almacen_secciones_nueva(id)
    )""")
    cur.execute(
        "INSERT INTO almacen_ubicaciones_nueva "
        "(id, seccion_id, almacen_id, codigo, fila, columna, capacidad_palets, alto_m, ancho_m, "
        "fondo_m, activa) SELECT u.id, u.seccion_id, sec.almacen_id, u.codigo, u.fila, "
        "u.columna, u.capacidad_palets, u.alto_m, u.ancho_m, u.fondo_m, u.activa "
        "FROM almacen_ubicaciones u JOIN almacen_secciones_nueva sec ON sec.id=u.seccion_id"
    )
    cur.execute("DROP TABLE almacen_ubicaciones")
    cur.execute("DROP TABLE almacen_secciones")
    cur.execute("ALTER TABLE almacen_secciones_nueva RENAME TO almacen_secciones")
    cur.execute("ALTER TABLE almacen_ubicaciones_nueva RENAME TO almacen_ubicaciones")


def _connect():
    if DATABASE_URL:
        import psycopg2

        return PostgresConnection(psycopg2.connect(DATABASE_URL))

    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    return sqlite3.connect(DB_PATH, check_same_thread=False)


def init_db():
    global _DB_INITIALIZED

    if _DB_INITIALIZED:
        return
    with _DB_INIT_LOCK:
        if _DB_INITIALIZED:
            return
        conn = _connect()
        try:
            if DATABASE_URL:
                _init_postgres(conn)
            else:
                _init_sqlite(conn)
            _DB_INITIALIZED = True
        finally:
            conn.close()


def get_conn():
    init_db()
    return _connect()
